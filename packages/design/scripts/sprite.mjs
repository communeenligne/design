// Generates icons/sprite.svg (a sheet of <symbol>) from the icons/*.svg files, all 24 × 24, stroke 1.5 and inherited
// color (currentColor). "node scripts/sprite.mjs --check" fails if the sheet is not up to date, or if an icon does
// not follow the common format.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const FOLDER = fileURLToPath(new URL('../icons/', import.meta.url))
const TARGET = `${FOLDER}sprite.svg`
const HEADER = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'

export const icons = () => readdirSync(FOLDER).filter((file) => file.endsWith('.svg') && file !== 'sprite.svg').sort()

export const generate = () => {
    const symbols = icons().map((file) => {
        const svg = readFileSync(FOLDER + file, 'utf8').trim()

        if (!svg.startsWith(HEADER) || !svg.endsWith('</svg>')) {
            throw new Error(`${file} does not follow the common format (24 × 24, stroke 1.5, currentColor).`)
        }

        if (/(fill|stroke)="#|stroke-width="(?!1\.5")/.test(svg.slice(HEADER.length))) {
            throw new Error(`${file}: color or stroke width specific to a path.`)
        }

        const body = svg.slice(HEADER.length, -'</svg>'.length)

        return `<symbol id="${file.slice(0, -4)}" viewBox="0 0 24 24">${body}</symbol>`
    })

    return `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">\n<!-- @communeenligne/design: sheet generated by scripts/sprite.mjs (npm run generate), do not edit. Licenses: icons/LICENSES.md. -->\n${symbols.join('\n')}\n</svg>\n`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const content = generate()

    if (process.argv.includes('--check')) {
        if (readFileSync(TARGET, 'utf8') !== content) {
            console.error('icons/sprite.svg is not up to date: run "npm run generate".')
            process.exit(1)
        }
        console.log(`icons/sprite.svg is up to date (${icons().length} icons).`)
    } else {
        writeFileSync(TARGET, content)
        console.log(`icons/sprite.svg generated (${icons().length} icons).`)
    }
}
