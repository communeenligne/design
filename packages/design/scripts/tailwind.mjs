// Generates tailwind.css (Tailwind 4 @theme block) from the foundations: each utility points to the package variable,
// never to a value. "node scripts/tailwind.mjs --check" fails if the file is not up to date.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { readTokens } from '../tools/tokens.mjs'

const TARGET = fileURLToPath(new URL('../tailwind.css', import.meta.url))

// Package prefix → Tailwind 4 namespace (first match wins).
const NAMESPACES = [
    ['cel-color-', 'color-'],
    ['cel-font-weight-', 'font-weight-'],
    ['cel-font-', 'font-'],
    ['cel-text-', 'text-'],
    ['cel-leading-', 'leading-'],
    ['cel-tracking-', 'tracking-'],
    ['cel-radius-', 'radius-'],
    ['cel-shadow-', 'shadow-'],
    ['cel-ease-', 'ease-'],
]

const NAMED = {
    'cel-width-content': 'container-content',
    'cel-width-narrow': 'container-narrow',
    'cel-width-reading': 'container-reading',
    'cel-space-section': 'spacing-section',
}

export const generate = () => {
    const { tokens } = readTokens()
    const lines = []

    for (const token of tokens) {
        const namespace = NAMESPACES.find(([prefix]) => token.name.startsWith(prefix))

        if (namespace) {
            lines.push(`    --${namespace[1]}${token.name.slice(namespace[0].length)}: var(--${token.name});`)
        } else if (NAMED[token.name]) {
            lines.push(`    --${NAMED[token.name]}: var(--${token.name});`)
        } else if (token.name.startsWith('cel-breakpoint-')) {
            // Tailwind 4 breakpoints are in rem (16 px); var() is not allowed in @media.
            lines.push(`    --breakpoint-${token.name.slice('cel-breakpoint-'.length)}: ${parseInt(token.light, 10) / 16}rem;`)
        }
    }

    return `/*
 * @communeenligne/design: Tailwind 4 theme. File generated by scripts/tailwind.mjs from the foundations: do not edit
 * it by hand (npm run generate).
 *
 * @theme inline: each utility writes var(--cel-…) in the page; the dark theme (.cel-dark) therefore applies without a
 * dark: variant. Examples: bg-background, text-primary, border-line, rounded-md, shadow-button, text-15, font-extrabold,
 * max-w-content, py-section; breakpoints phone: (640 px and more), max-phone: (less than 640 px).
 */

@import './foundations/index.css';

@theme inline {
${lines.join('\n')}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const content = generate()

    if (process.argv.includes('--check')) {
        if (readFileSync(TARGET, 'utf8') !== content) {
            console.error('tailwind.css is not up to date: run "npm run generate".')
            process.exit(1)
        }
        console.log('tailwind.css is up to date.')
    } else {
        writeFileSync(TARGET, content)
        console.log('tailwind.css generated.')
    }
}
