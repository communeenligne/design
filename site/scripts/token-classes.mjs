// Stylesheet generated at each build from the foundations (src/styles/tokens.generated.css, not versioned): one class
// per variable, which sets its value in --doc-v (and, for a color, its light and dark values). The foundation pages use
// it for their samples, without a style attribute and without copying a value.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { readTokens, resolve } from '@communeenligne/design/tools/tokens.mjs'

const { tokens } = readTokens()
const rules = tokens.map((token) => {
    const color = token.name.startsWith('cel-color-')
    const values = color ? ` --doc-light: ${resolve(tokens, token.name, 'light')}; --doc-dark: ${resolve(tokens, token.name, 'dark')};` : ''

    return `.doc-v-${token.name} { --doc-v: var(--${token.name});${values} }`
})

writeFileSync(fileURLToPath(new URL('../src/styles/tokens.generated.css', import.meta.url)), `/* Generated by scripts/token-classes.mjs from the foundations: do not edit. */\n${rules.join('\n')}\n`)
console.log(`Variable classes generated (${rules.length}).`)
